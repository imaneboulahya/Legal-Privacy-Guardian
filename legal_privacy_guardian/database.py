from contextlib import closing, contextmanager
from datetime import datetime
import json
import sqlite3
from pathlib import Path
from typing import Iterator, Protocol

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb


Database = Path | str


class _Row(Protocol):
    def __getitem__(self, key: str) -> object: ...


class _Cursor(Protocol):
    @property
    def lastrowid(self) -> int | None: ...

    @property
    def rowcount(self) -> int: ...

    def fetchone(self) -> _Row | None: ...

    def fetchall(self) -> list[_Row]: ...


class _Connection(Protocol):
    def execute(
        self, query: str, parameters: tuple[object, ...] = ()
    ) -> _Cursor: ...


@contextmanager
def _connect(database: Database) -> Iterator[_Connection]:
    if isinstance(database, Path):
        with closing(sqlite3.connect(database)) as connection:
            connection.row_factory = sqlite3.Row
            with connection:
                yield connection
        return

    with psycopg.connect(database, row_factory=dict_row) as connection:
        yield connection


def init_db(database: Database) -> None:
    with _connect(database) as connection:
        if isinstance(database, Path):
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS scan_reports (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    filename TEXT NOT NULL,
                    scanned_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    findings TEXT NOT NULL
                )
                """
            )
            return

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS scan_reports (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                filename TEXT NOT NULL,
                scanned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                findings JSONB NOT NULL
            )
            """
        )


def save_scan(database: Database, filename: str, findings: dict[str, int]) -> int:
    with _connect(database) as connection:
        if isinstance(database, Path):
            cursor = connection.execute(
                "INSERT INTO scan_reports (filename, findings) VALUES (?, ?)",
                (filename, json.dumps(findings, ensure_ascii=False)),
            )
            return int(cursor.lastrowid)

        row = connection.execute(
            """
            INSERT INTO scan_reports (filename, findings)
            VALUES (%s, %s)
            RETURNING id
            """,
            (filename, Jsonb(findings)),
        ).fetchone()
        return int(row["id"])


def get_scan(database: Database, scan_id: int) -> dict[str, object] | None:
    with _connect(database) as connection:
        row = connection.execute(
            "SELECT id, filename, scanned_at, findings FROM scan_reports WHERE id = "
            + ("%s" if isinstance(database, str) else "?"),
            (scan_id,),
        ).fetchone()
    return _row_to_scan(row) if row else None


def delete_scan(database: Database, scan_id: int) -> bool:
    with _connect(database) as connection:
        placeholder = "%s" if isinstance(database, str) else "?"
        cursor = connection.execute(
            f"DELETE FROM scan_reports WHERE id = {placeholder}", (scan_id,)
        )
        return cursor.rowcount > 0


def delete_all_scans(database: Database) -> int:
    with _connect(database) as connection:
        cursor = connection.execute("DELETE FROM scan_reports")
        return cursor.rowcount


def list_recent_scans(database: Database, limit: int = 10) -> list[dict[str, object]]:
    limit = max(1, min(limit, 100))
    with _connect(database) as connection:
        placeholder = "%s" if isinstance(database, str) else "?"
        rows = connection.execute(
            f"""
            SELECT id, filename, scanned_at, findings
            FROM scan_reports
            ORDER BY id DESC
            LIMIT {placeholder}
            """,
            (limit,),
        ).fetchall()

    return [_row_to_scan(row) for row in rows]


def _row_to_scan(row: _Row) -> dict[str, object]:
    findings = row["findings"]
    if isinstance(findings, str):
        findings = json.loads(findings)
    scanned_at = row["scanned_at"]
    if isinstance(scanned_at, datetime):
        scanned_at = scanned_at.isoformat(sep=" ", timespec="seconds")
    return {
        "id": row["id"],
        "filename": row["filename"],
        "scanned_at": scanned_at,
        "findings": findings,
    }
