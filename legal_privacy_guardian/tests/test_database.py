import sys
import unittest
from datetime import datetime
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from database import get_scan, init_db, list_recent_scans, save_scan


class FakeCursor:
    def __init__(self, row=None, rows=None, rowcount=1):
        self.row = row
        self.rows = rows or []
        self.rowcount = rowcount

    def fetchone(self):
        return self.row

    def fetchall(self):
        return self.rows


class FakePostgresConnection:
    def __init__(self, cursor):
        self.cursor = cursor
        self.calls = []

    def __enter__(self):
        return self

    def __exit__(self, *_args):
        return False

    def execute(self, query, parameters=()):
        self.calls.append((query, parameters))
        return self.cursor


class PostgresDatabaseTests(unittest.TestCase):
    def test_init_creates_postgres_schema(self):
        connection = FakePostgresConnection(FakeCursor())
        with patch("database.psycopg.connect", return_value=connection):
            init_db("postgresql://localhost/guardian")

        self.assertIn("JSONB NOT NULL", connection.calls[0][0])
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", connection.calls[0][0])

    def test_save_scan_uses_returning_and_jsonb(self):
        connection = FakePostgresConnection(FakeCursor(row={"id": 12}))
        with patch("database.psycopg.connect", return_value=connection):
            scan_id = save_scan(
                "postgresql://localhost/guardian",
                "contract.txt",
                {"email": 1},
            )

        query, parameters = connection.calls[0]
        self.assertEqual(scan_id, 12)
        self.assertIn("RETURNING id", query)
        self.assertEqual(parameters[0], "contract.txt")
        self.assertEqual(parameters[1].obj, {"email": 1})

    def test_postgres_rows_are_normalized_for_api_responses(self):
        row = {
            "id": 12,
            "filename": "contract.txt",
            "scanned_at": datetime(2026, 10, 21, 11, 0),
            "findings": {"email": 1},
        }
        connection = FakePostgresConnection(FakeCursor(row=row, rows=[row]))
        with patch("database.psycopg.connect", return_value=connection):
            single = get_scan("postgresql://localhost/guardian", 12)
            recent = list_recent_scans("postgresql://localhost/guardian", 500)

        self.assertEqual(single, recent[0])
        self.assertEqual(single["scanned_at"], "2026-10-21 11:00:00")
        self.assertEqual(single["findings"], {"email": 1})
        self.assertIn("LIMIT %s", connection.calls[-1][0])
        self.assertEqual(connection.calls[-1][1], (100,))


if __name__ == "__main__":
    unittest.main()
